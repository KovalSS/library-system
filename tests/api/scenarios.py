def S(id, kind, title, op, req, method, path, status, *, bdd=None, body=None,
      auth=True, prefer=None, accept="application/json", content_type=None,
      headers=(), check=None):
    return {
        "id": id, "kind": kind, "title": title, "op": op, "req": req, "bdd": bdd,
        "request": {"method": method, "path": path, "body": body, "auth": auth,
                    "prefer": prefer, "accept": accept},
        "expect": {"status": status, "content_type": content_type,
                   "headers": list(headers), "check": check},
    }


def P(*a, **k):
    return S(a[0], "positive", *a[1:], **k)


def N(*a, **k):
    return S(a[0], "negative", *a[1:], **k)


